/*
 * WasteScan – tools/generate-sample.js
 * Regenerates the bundled DEMONSTRATION images (synthetic, not real satellite data):
 *   assets/sample-images/*.png          – the images themselves
 *   assets/sample-images/sample-data.js – the same images as data-URLs. Browsers
 *     treat <img> loaded from file:// as cross-origin, which would block canvas
 *     pixel access, so the app loads the samples from this script instead.
 * Run:  node tools/generate-sample.js
 */
'use strict';
var fs = require('fs'), path = require('path');
var scene = require('./scene.js');
var png = require('./png.js');

var outDir = path.join(__dirname, '..', 'assets', 'sample-images');
fs.mkdirSync(outDir, { recursive: true });

var samples = [
  { id: 'sample-1', file: 'sample-rural-with-dumps.png', title: 'Synthetic rural scene – simulated dump sites',
    description: 'Computer-generated farmland, forest, river, village and four simulated dump sites.', opts: { width: 800, height: 560, seed: 20240611 } },
  { id: 'sample-2', file: 'sample-rural-clean.png', title: 'Synthetic rural scene – no dumping',
    description: 'Computer-generated scene with no simulated dumping, useful to check for false positives.', opts: { width: 640, height: 448, seed: 777, dumps: false } }
];

var js = '/* Generated by tools/generate-sample.js – synthetic demonstration images (not real satellite imagery). */\n' +
         'window.WS = window.WS || {};\nWS.SAMPLES = [\n';
samples.forEach(function (s, i) {
  var sc = scene.generateScene(s.opts);
  var buf = png.encodePNG(sc.width, sc.height, sc.rgba);
  fs.writeFileSync(path.join(outDir, s.file), buf);
  console.log(s.file, sc.width + 'x' + sc.height, Math.round(buf.length / 1024) + ' KB');
  js += '  { id: ' + JSON.stringify(s.id) + ', file: ' + JSON.stringify(s.file) + ', title: ' + JSON.stringify(s.title) +
        ', description: ' + JSON.stringify(s.description) + ', width: ' + sc.width + ', height: ' + sc.height +
        ', dataUrl: "data:image/png;base64,' + buf.toString('base64') + '" }' + (i < samples.length - 1 ? ',' : '') + '\n';
});
js += '];\n';
fs.writeFileSync(path.join(outDir, 'sample-data.js'), js);
console.log('sample-data.js', Math.round(js.length / 1024) + ' KB');
